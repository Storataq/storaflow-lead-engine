export const COUNTRY_BY_CODE: Record<string, CountryRecord> = Object.fromEntries(
  COUNTRIES.map((country) => [country.code, country]),
);

export function isCountryCode(value: string): boolean {
  return Object.prototype.hasOwnProperty.call(
    COUNTRY_BY_CODE,
    value.toUpperCase(),
  );
}

export function toE164Example(countryCode: string): string | null {
  const country = COUNTRY_BY_CODE[countryCode.toUpperCase()];
  if (!country) return null;
  return `+${country.callingCode}${country.nationalNumberExample}`;
}
